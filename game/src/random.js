// A small seeded random generator (mulberry32) plus the helpers the game
// uses, so a screenshot scene or a replay with the same seed always unfolds
// the same way.

export function makeRng(seed) {
  let state = (seed >>> 0) || 1;
  const next = () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    range: (min, max) => min + next() * (max - min),
    int: (min, max) => Math.floor(min + next() * (max - min + 1)),
    pick: (items) => items[Math.floor(next() * items.length)],
    chance: (p) => next() < p,
  };
}

/** Turn a short text seed (a URL's seed= word) into a number for makeRng. */
export function seedFromText(text, fallback) {
  if (text === null || text === undefined || text === '') return fallback;
  const asNumber = Number(text);
  if (Number.isFinite(asNumber)) return asNumber >>> 0;
  let hash = 2166136261;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}
